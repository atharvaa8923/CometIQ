def build_description(intro: str, req: list[str], pref: list[str]) -> str:
    return (
        f"{intro}\n\nYou will report to the team lead and work on high-visibility projects.\n\n"
        "Required qualifications:\n" + "\n".join(f"- {r}" for r in req)
        + "\n\nPreferred qualifications:\n" + "\n".join(f"- {p}" for p in pref)
    )


